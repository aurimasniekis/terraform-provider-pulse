func init() { registerResource(NewInboundWebhookResource) }

// hookNameRE is the name pattern of inbound and outbound webhooks.
var hookNameRE = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,47}$`)

var (
	_ resource.ResourceWithImportState = (*inboundWebhookResource)(nil)
)

type inboundWebhookResource struct{ baseResource }

// NewInboundWebhookResource returns the pulse_inbound_webhook resource.
func NewInboundWebhookResource() resource.Resource { return &inboundWebhookResource{} }

type inboundWebhookModel struct {
	ID            types.String `tfsdk:"id"`
	Name          types.String `tfsdk:"name"`
	Kind          types.String `tfsdk:"kind"`
	Subject       types.String `tfsdk:"subject"`
	Enabled       types.Bool   `tfsdk:"enabled"`
	Config        types.Object `tfsdk:"config"`
	Secret        types.String `tfsdk:"secret"`
	SecretVersion types.String `tfsdk:"secret_version"`
	URL           types.String `tfsdk:"url"`
}

type inboundWebhookConfigModel struct {
	Type            types.String `tfsdk:"type"`
	Header          types.String `tfsdk:"header"`
	Prefix          types.String `tfsdk:"prefix"`
	Encoding        types.String `tfsdk:"encoding"`
	TimestampHeader types.String `tfsdk:"timestamp_header"`
	ToleranceSec    types.Int64  `tfsdk:"tolerance_sec"`
}

var inboundWebhookConfigTypes = map[string]attr.Type{
	"type": types.StringType, "header": types.StringType, "prefix": types.StringType, "encoding": types.StringType,
	"timestamp_header": types.StringType, "tolerance_sec": types.Int64Type,
}

func (r *inboundWebhookResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_inbound_webhook"
}

