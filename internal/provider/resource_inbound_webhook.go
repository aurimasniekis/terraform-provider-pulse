// inboundSubjectDefault plans the server's default subject when none is configured.
type inboundSubjectDefault struct{}

func (inboundSubjectDefault) Description(context.Context) string {
	return "Defaults to evt.hook.<name>.received."
}

func (m inboundSubjectDefault) MarkdownDescription(ctx context.Context) string {
	return m.Description(ctx)
}

func (inboundSubjectDefault) PlanModifyString(ctx context.Context, req planmodifier.StringRequest, resp *planmodifier.StringResponse) {
	if !req.ConfigValue.IsNull() || req.Plan.Raw.IsNull() {
		return
	}
	var name types.String
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, path.Root("name"), &name)...)
	if name.IsUnknown() || name.IsNull() {
		return
	}
	resp.PlanValue = types.StringValue(defaultHookSubject(name.ValueString()))
}

func defaultHookSubject(name string) string {
	return "evt.hook." + strings.ReplaceAll(name, "_", "-") + ".received"
}

func (m *inboundWebhookModel) input(ctx context.Context, diags *diag.Diagnostics) client.InboundHookInput {
	in := client.InboundHookInput{Name: m.Name.ValueString(), Kind: m.Kind.ValueString(), Enabled: m.Enabled.ValueBool()}
	if !m.Subject.IsUnknown() {
		in.Subject = m.Subject.ValueString()
	}
	if !m.Config.IsNull() && !m.Config.IsUnknown() {
		var c inboundWebhookConfigModel
		diags.Append(m.Config.As(ctx, &c, basetypes.ObjectAsOptions{})...)
		in.Config = client.InboundHookConfig{Type: c.Type.ValueString(), Header: c.Header.ValueString(), Prefix: c.Prefix.ValueString(),
			Encoding: c.Encoding.ValueString(), TimestampHeader: c.TimestampHeader.ValueString(), ToleranceSec: c.ToleranceSec.ValueInt64()}
	}
	return in
}

// fill copies the server's view; secret and secret_version are kept. An all-default config is null unless the
// configuration (or state) has an empty config object.
func (m *inboundWebhookModel) fill(h *client.InboundHook) {
	m.ID = types.StringValue(h.ID)
	m.Name = types.StringValue(h.Name)
	m.Kind = types.StringValue(h.Kind)
	m.Subject = types.StringValue(h.Subject)
	m.Enabled = types.BoolValue(h.Enabled)
	m.URL = types.StringValue(h.URL)
	c := h.Config
	if c == (client.InboundHookConfig{}) && (m.Config.IsNull() || m.Config.IsUnknown()) {
		m.Config = types.ObjectNull(inboundWebhookConfigTypes)
	} else {
		tol := types.Int64Null()
		if c.ToleranceSec != 0 {
			tol = types.Int64Value(c.ToleranceSec)
		}
		m.Config = types.ObjectValueMust(inboundWebhookConfigTypes, map[string]attr.Value{
			"type": optString(c.Type), "header": optString(c.Header), "prefix": optString(c.Prefix), "encoding": optString(c.Encoding),
			"timestamp_header": optString(c.TimestampHeader), "tolerance_sec": tol,
		})
	}
	if m.Secret.IsUnknown() {
		m.Secret = types.StringNull()
	}
}

func (r *inboundWebhookResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan inboundWebhookModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	in := plan.input(ctx, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	if !plan.Secret.IsUnknown() {
		in.Secret = plan.Secret.ValueString()
	}
	res, err := r.client.CreateInboundHook(ctx, in)
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot create inbound webhook", err)
		return
	}
	if res.Secret != "" {
		plan.Secret = types.StringValue(res.Secret)
	}
	plan.fill(&res.Hook)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *inboundWebhookResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state inboundWebhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	h, err := r.client.GetInboundHook(ctx, state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot read inbound webhook", err)
		return
	}
	state.fill(h)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *inboundWebhookResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state inboundWebhookModel
	var configSecret types.String
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("secret"), &configSecret)...)
	if resp.Diagnostics.HasError() {
		return
	}
	in := plan.input(ctx, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	secret := state.Secret
	switch {
	case !configSecret.IsNull():
		if !configSecret.Equal(state.Secret) {
			in.Secret = configSecret.ValueString()
			secret = configSecret
		}
	case !plan.SecretVersion.Equal(state.SecretVersion):
		in.RotateSecret = true
	}
	res, err := r.client.UpdateInboundHook(ctx, state.ID.ValueString(), in)
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot update inbound webhook", err)
		return
	}
	if in.RotateSecret {
		secret = optString(res.Secret)
	}
	plan.Secret = secret
	plan.fill(&res.Hook)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *inboundWebhookResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state inboundWebhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteInboundHook(ctx, state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		apiError(&resp.Diagnostics, "Cannot delete inbound webhook", err)
	}
}

func (r *inboundWebhookResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
