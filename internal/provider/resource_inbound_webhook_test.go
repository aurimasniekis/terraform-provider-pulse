// attrIs and attrDiffers compare a state attribute with a value captured in an earlier step.
func attrIs(name, attr string, want *string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		got := s.RootModule().Resources[name].Primary.Attributes[attr]
		if got != *want {
			return fmt.Errorf("%s.%s changed", name, attr)
		}
		return nil
	}
}

func attrDiffers(name, attr string, old *string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		got := s.RootModule().Resources[name].Primary.Attributes[attr]
		if got == "" || got == *old {
			return fmt.Errorf("%s.%s was not replaced", name, attr)
		}
		return nil
	}
}

func TestAccInboundWebhook(t *testing.T) {
	testAccPreCheck(t)
	suffix := randName("x")[2:]
	name1, name2 := "ih-"+suffix, "ih_"+suffix
	const res = "pulse_inbound_webhook.h"
	var id, secret1, secret2 string
	resource.ParallelTest(t, resource.TestCase{
		PreCheck:                 func() { testAccPreCheck(t) },
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		CheckDestroy: checkGone(t, "pulse_inbound_webhook", func(ctx context.Context, c *client.Client, a map[string]string) error {
			_, err := c.GetInboundHook(ctx, a["id"])
			return err
		}),
		Steps: []resource.TestStep{
			{
				Config: inboundConfig(name1, "hmac", ""),
				Check: resource.ComposeAggregateTestCheckFunc(
					resource.TestCheckResourceAttr(res, "name", name1),
					resource.TestCheckResourceAttr(res, "kind", "hmac"),
					resource.TestCheckResourceAttr(res, "subject", "evt.hook."+name1+".received"),
					resource.TestCheckResourceAttr(res, "enabled", "true"),
					resource.TestCheckNoResourceAttr(res, "config"),
					resource.TestMatchResourceAttr(res, "url", regexpMust(`/hooks/`+name1+`$`)),
					resource.TestMatchResourceAttr(res, "secret", regexpMust(`^[A-Za-z0-9_-]{43}$`)),
					capture(res, "id", &id),
					capture(res, "secret", &secret1),
				),
			},
			{
				// Rename (subject default and URL follow), change kind, settings: in place, secret kept.
				Config: inboundConfig(name2, "secret", `
  enabled = false
  config = {
    header = "X-Token"
    type   = "tfacc.ping"
  }
`),
				ConfigPlanChecks: expectUpdate(res),
				Check: resource.ComposeAggregateTestCheckFunc(
					resource.TestCheckResourceAttr(res, "name", name2),
					resource.TestCheckResourceAttr(res, "kind", "secret"),
					resource.TestCheckResourceAttr(res, "subject", "evt.hook."+strings.ReplaceAll(name2, "_", "-")+".received"),
					resource.TestCheckResourceAttr(res, "enabled", "false"),
					resource.TestCheckResourceAttr(res, "config.header", "X-Token"),
					resource.TestCheckResourceAttr(res, "config.type", "tfacc.ping"),
					resource.TestCheckNoResourceAttr(res, "config.encoding"),
					resource.TestMatchResourceAttr(res, "url", regexpMust(`/hooks/`+name2+`$`)),
					attrIs(res, "id", &id),
					attrIs(res, "secret", &secret1),
				),
			},
			{ResourceName: res, ImportState: true, ImportStateVerify: true,
				ImportStateVerifyIgnore: []string{"secret", "secret_version"}},
			{
				// Rotation: a new secret generated by Pulse.
				Config: inboundConfig(name2, "hmac", `
  subject        = "evt.tfacc.hook.custom"
  secret_version = "2"
  config = {
    header           = "X-Sig"
    prefix           = "sha256="
    encoding         = "base64"
    timestamp_header = "X-Timestamp"
    tolerance_sec    = 60
  }
`),
				ConfigPlanChecks: expectUpdate(res),
				Check: resource.ComposeAggregateTestCheckFunc(
					resource.TestCheckResourceAttr(res, "subject", "evt.tfacc.hook.custom"),
					resource.TestCheckResourceAttr(res, "config.tolerance_sec", "60"),
					resource.TestCheckResourceAttr(res, "config.encoding", "base64"),
					resource.TestCheckResourceAttr(res, "enabled", "true"),
					attrDiffers(res, "secret", &secret1),
					capture(res, "secret", &secret2),
				),
			},
			{
				// A configured secret replaces the generated one in place.
				Config:           inboundConfig(name2, "github", `  secret = "configured-secret-0123456789"`),
				ConfigPlanChecks: expectUpdate(res),
				Check: resource.ComposeAggregateTestCheckFunc(
					resource.TestCheckResourceAttr(res, "secret", "configured-secret-0123456789"),
					resource.TestCheckResourceAttr(res, "subject", "evt.hook."+strings.ReplaceAll(name2, "_", "-")+".received"),
					resource.TestCheckNoResourceAttr(res, "config"),
				),
			},
			// Drift: deleted out of band → recreated with the configured secret.
			{
				PreConfig: oob(t, func(ctx context.Context, c *client.Client) error {
					h, err := c.ListInboundHooks(ctx)
					if err != nil {
						return err
					}
					for _, x := range h {
						if x.Name == name2 {
							return c.DeleteInboundHook(ctx, x.ID)
						}
					}
					return fmt.Errorf("hook %s not found", name2)
				}),
				Config:           inboundConfig(name2, "github", `  secret = "configured-secret-0123456789"`),
				ConfigPlanChecks: expectRecreate(res),
				Check:            resource.TestCheckResourceAttr(res, "secret", "configured-secret-0123456789"),
			},
		},
	})
}

func TestAccInboundWebhookInvalid(t *testing.T) {
	testAccPreCheck(t)
	resource.ParallelTest(t, resource.TestCase{
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		Steps: []resource.TestStep{
			{Config: inboundConfig("Bad Name", "hmac", ""), ExpectError: regexpMust(`must be 1-48 lowercase`)},
			{Config: inboundConfig(randName("ih"), "hmac", `  secret = "short"`), ExpectError: regexpMust(`length`)},
			{Config: inboundConfig(randName("ih"), "hmac", `  subject = "app.not.events.here"`), ExpectError: regexpMust(`evt`)},
		},
	})
}

func inboundConfig(name, kind, extra string) string {
	return fmt.Sprintf(`
resource "pulse_inbound_webhook" "h" {
  name = %q
  kind = %q
%s
}
`, name, kind, extra)
}
