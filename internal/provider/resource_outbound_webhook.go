func init() { registerResource(NewOutboundWebhookResource) }

var (
	outboundFilterRE = regexp.MustCompile(`^evt\.(>|((\*|[a-z0-9_-]+)\.)*(\*|>|[a-z0-9_-]+))$`)
	headerNameRE     = regexp.MustCompile(`^[A-Za-z0-9-]{1,64}$`)
)

var _ resource.ResourceWithImportState = (*outboundWebhookResource)(nil)

type outboundWebhookResource struct{ baseResource }

// NewOutboundWebhookResource returns the pulse_outbound_webhook resource.
func NewOutboundWebhookResource() resource.Resource { return &outboundWebhookResource{} }

type outboundWebhookModel struct {
	ID            types.String `tfsdk:"id"`
	Name          types.String `tfsdk:"name"`
	URL           types.String `tfsdk:"url"`
	Filter        types.String `tfsdk:"filter"`
	Headers       types.Map    `tfsdk:"headers"`
	Paused        types.Bool   `tfsdk:"paused"`
	Secret        types.String `tfsdk:"secret"`
	SecretVersion types.String `tfsdk:"secret_version"`
	Consumer      types.String `tfsdk:"consumer"`
}

func (r *outboundWebhookResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_outbound_webhook"
}

func (r *outboundWebhookResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "An outbound webhook: Pulse POSTs every event matching `filter` to `url`, one at a time and in order, " +
			"retrying with backoff and signing each request with HMAC-SHA256 using `secret`. Only events published after the " +
			"webhook is created are delivered.\n\n" +
			"The URL must not point at private, loopback or link-local addresses unless the server allows them " +
			"(`PULSE_OUTBOUND_ALLOW`). The signing secret is either set with `secret` or generated by Pulse when the webhook is " +
			"created; Pulse never returns it again, so the provider keeps it in state (sensitive). Change `secret_version` to have " +
			"Pulse generate a new one. Import with the webhook ID; an imported webhook has no `secret` in state until you set " +
			"`secret` or change `secret_version`.",
		Attributes: map[string]schema.Attribute{
			"id": idAttribute("Webhook ID."),
			"name": schema.StringAttribute{MarkdownDescription: "Name, unique among outbound webhooks: lowercase letters, digits, `_` " +
				"and `-`, at most 48 characters, starting with a letter or digit.", Required: true,
				Validators: []validator.String{stringvalidator.RegexMatches(hookNameRE,
					"must be 1-48 lowercase letters, digits, '_' or '-', starting with a letter or digit")}},
			"url": schema.StringAttribute{MarkdownDescription: "Endpoint the events are POSTed to (`http` or `https`, without " +
				"credentials; send those in `headers`).", Required: true,
				Validators: []validator.String{stringvalidator.LengthBetween(1, 2048)}},
			"filter": schema.StringAttribute{MarkdownDescription: "Subject filter under `evt.`, e.g. `evt.>` (everything) or " +
				"`evt.home.*.created`. Wildcards: `*` matches one token, `>` (last) the rest. Changing it keeps the delivery position.",
				Required: true, Validators: []validator.String{stringvalidator.LengthAtMost(256),
					stringvalidator.RegexMatches(outboundFilterRE, "must be a subject filter under evt., e.g. evt.> or evt.home.*.created")}},
			"headers": schema.MapAttribute{MarkdownDescription: "Extra request headers, e.g. `Authorization`. `Host`, `Content-Type`, " +
				"`Content-Length` and `Pulse-*` cannot be set. Sensitive, because they usually carry credentials.",
				ElementType: types.StringType, Optional: true, Computed: true, Sensitive: true,
				Default:    mapdefault.StaticValue(mapOf(nil)),
				Validators: []validator.Map{mapvalidator.KeysAre(stringvalidator.RegexMatches(headerNameRE, "must be 1-64 letters, digits or '-'"))}},
			"paused": schema.BoolAttribute{MarkdownDescription: "Pause deliveries. Events keep queueing and are delivered after " +
				"resuming. Default `false`.", Optional: true, Computed: true, Default: booldefault.StaticBool(false)},
			"secret": schema.StringAttribute{
				MarkdownDescription: "Signing secret (at least 16 characters). Leave it unset to have Pulse generate one " +
					"(`whsec_…`) at creation; the generated value is stored in state. Changing a configured value updates it in place.",
				Optional: true, Computed: true, Sensitive: true,
				Validators:    []validator.String{stringvalidator.LengthBetween(16, 256)},
				PlanModifiers: []planmodifier.String{configurableSecretPlanModifier{versionAttr: "secret_version"}},
			},
			"secret_version": schema.StringAttribute{
				MarkdownDescription: "Arbitrary value. When `secret` is not set, changing it (including setting it for the first " +
					"time, e.g. after an import) makes Pulse generate a new secret, which is stored in state. Requests are signed " +
					"with the new secret from then on. Has no effect while `secret` is set.",
				Optional: true,
			},
			"consumer": computedString("Name of the JetStream consumer that tracks the delivery position."),
		},
	}
}

func (m *outboundWebhookModel) fill(h *client.OutboundHook) {
	m.ID = types.StringValue(h.ID)
	m.Name = types.StringValue(h.Name)
	m.URL = types.StringValue(h.URL)
	m.Filter = types.StringValue(h.Filter)
	m.Headers = mapOf(h.Headers)
	m.Paused = types.BoolValue(h.Paused)
	m.Consumer = types.StringValue(h.Consumer)
	if m.Secret.IsUnknown() {
		m.Secret = types.StringNull()
	}
}

func (r *outboundWebhookResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan outboundWebhookModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	in := client.OutboundHookInput{Name: plan.Name.ValueString(), Filter: plan.Filter.ValueString(), URL: plan.URL.ValueString(),
		Headers: stringMapOf(ctx, plan.Headers, &resp.Diagnostics)}
	if !plan.Secret.IsUnknown() {
		in.Secret = plan.Secret.ValueString()
	}
	if resp.Diagnostics.HasError() {
		return
	}
	res, err := r.client.CreateOutboundHook(ctx, in)
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot create outbound webhook", err)
		return
	}
	if res.Secret != "" {
		plan.Secret = types.StringValue(res.Secret)
	}
	h := &res.Hook
	if plan.Paused.ValueBool() {
		p, err := r.client.SetOutboundHookPaused(ctx, h.ID, true)
		if err != nil {
			plan.fill(h)
			resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
			apiError(&resp.Diagnostics, "Outbound webhook created but could not be paused", err)
			return
		}
		h = p
	}
	plan.fill(h)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *outboundWebhookResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state outboundWebhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	h, err := r.client.GetOutboundHook(ctx, state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot read outbound webhook", err)
		return
	}
	state.fill(h)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *outboundWebhookResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state outboundWebhookModel
	var configSecret types.String
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("secret"), &configSecret)...)
	if resp.Diagnostics.HasError() {
		return
	}
	id := state.ID.ValueString()
	in := client.OutboundHookInput{Name: plan.Name.ValueString(), Filter: plan.Filter.ValueString(), URL: plan.URL.ValueString(),
		Headers: stringMapOf(ctx, plan.Headers, &resp.Diagnostics)}
	if resp.Diagnostics.HasError() {
		return
	}
	secret := state.Secret
	switch {
	case !configSecret.IsNull():
		if !configSecret.Equal(state.Secret) {
			in.Secret = configSecret.ValueString()
			secret = configSecret
		}
	case !plan.SecretVersion.Equal(state.SecretVersion):
		in.RotateSecret = true
	}
	res, err := r.client.UpdateOutboundHook(ctx, id, in)
	if err != nil {
		apiError(&resp.Diagnostics, "Cannot update outbound webhook", err)
		return
	}
	if in.RotateSecret {
		secret = optString(res.Secret)
	}
	plan.Secret = secret
	h := &res.Hook
	if want := plan.Paused.ValueBool(); h.Paused != want {
		p, err := r.client.SetOutboundHookPaused(ctx, id, want)
		if err != nil {
			plan.fill(h)
			resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
			apiError(&resp.Diagnostics, "Cannot pause or resume outbound webhook", err)
			return
		}
		h = p
	}
	plan.fill(h)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *outboundWebhookResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state outboundWebhookModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteOutboundHook(ctx, state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		apiError(&resp.Diagnostics, "Cannot delete outbound webhook", err)
	}
}

func (r *outboundWebhookResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
